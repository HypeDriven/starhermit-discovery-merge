// Writes the shared rules (src/engine/rng.js, src/engine/rules.js,
// src/content.js) into score-script.js between its `// RULES:BEGIN` and
// `// RULES:END` markers. The platform runs score-script.js as one classic
// script (no imports, no Date or Math.random), so each ES module becomes a
// function scope whose exports form an object (`Rng`, `Rules`, `Content`); its
// imports read those objects. The practice generator's wall-clock seed (never
// called by the script) becomes a constant, so nothing in the block reads the
// host's time.
//
//   node tools/build-score-script.mjs          rewrite the block
//   node tools/build-score-script.mjs --check  exit 1 when the block is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const MODULES = [
  { name: 'Rng', file: 'src/engine/rng.js' },
  { name: 'Rules', file: 'src/engine/rules.js' },
  { name: 'Content', file: 'src/content.js' },
];
const BY_FILE = { './rng.js': 'Rng', './engine/rng.js': 'Rng', './engine/rules.js': 'Rules' };
const PRACTICE_CLOCK = "hashString('practice:' + Date.now() + ':' + Math.random())";

function convert({ name, file }) {
  let src = readFileSync(ROOT + file, 'utf8');
  const exported = [];
  src = src.replace(/^import \{([^}]*)\} from '([^']+)';$/gm, (_, names, from) => {
    const mod = BY_FILE[from];
    if (!mod) throw new Error(`${file}: unknown import ${from}`);
    return `const {${names}} = ${mod};`;
  });
  src = src.replace(/^export \{([^}]*)\};$/gm, (_, names) => { exported.push(...names.split(',').map((s) => s.trim()).filter(Boolean)); return ''; });
  src = src.replace(/^export (const|let|function|class) ([A-Za-z_$][\w$]*)/gm, (_, kind, id) => {
    exported.push(id);
    return `${kind} ${id}`;
  });
  if (/^\s*(import|export)\b/m.test(src)) throw new Error(`${file}: an import/export the build does not handle`);
  if (file.endsWith('content.js')) {
    if (!src.includes(PRACTICE_CLOCK)) throw new Error('content.js: the practice seed line changed; update tools/build-score-script.mjs');
    src = src.replace(PRACTICE_CLOCK, "hashString('practice:server')");
  }
  if (/\bDate\b|Math\.random|performance/.test(src)) throw new Error(`${file}: reads the host's clock or dice`);
  return `var ${name} = (function () {\n${src.trim()}\nreturn { ${[...new Set(exported)].join(', ')} };\n})();`;
}

const block = [
  '// RULES:BEGIN — generated by tools/build-score-script.mjs from src/engine/{rng,rules}.js and src/content.js; do not edit.',
  ...MODULES.map(convert),
  '// RULES:END',
].join('\n');

const file = ROOT + 'score-script.js';
const cur = readFileSync(file, 'utf8');
const a = cur.indexOf('// RULES:BEGIN'), b = cur.indexOf('// RULES:END');
if (a < 0 || b < 0) throw new Error('score-script.js has no RULES block');
const next = cur.slice(0, a) + block + cur.slice(b + '// RULES:END'.length);
if (process.argv.includes('--check')) {
  if (next !== cur) { console.error('score-script.js: the RULES block is stale — run node tools/build-score-script.mjs'); process.exit(1); }
  console.log('score-script.js: RULES block current');
} else if (next !== cur) {
  writeFileSync(file, next);
  console.log('score-script.js: RULES block rewritten');
} else console.log('score-script.js: RULES block current');
