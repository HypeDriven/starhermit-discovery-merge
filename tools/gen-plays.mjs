// Writes the play scripts in tests/native/ that drive the real UI through
// whole rounds, from the rules: src/engine/rules.js and src/content.js run
// here in node, a greedy player (deliver, else merge, else tap a Field Kit)
// picks each action, and the script moves the board focus there with the
// arrow keys, selects / confirms with Enter, delivers through the Requests
// drawer's Deliver button (the render check plays at 960×540, the compact
// layout) and waits out the input lock (260 ms) before the next action.
// Journey boards are seeded by their content, so the scripts replay exactly.
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { applyCommand, createGame, legalActions } from '../src/engine/rules.js';
import { journeyLevel } from '../src/content.js';

const ROOT = new URL('..', import.meta.url).pathname;

class Script {
  constructor(head, cols) { this.lines = head.map((l) => `# ${l}`); this.focus = 0; this.cols = cols; }
  add(...l) { this.lines.push(...l); return this; }
  moveTo(cell) {
    const r = Math.floor(cell / this.cols), c = cell % this.cols;
    let fr = Math.floor(this.focus / this.cols), fc = this.focus % this.cols;
    while (fr < r) { this.add('key ArrowDown 1', 'frames 1'); fr++; }
    while (fr > r) { this.add('key ArrowUp 1', 'frames 1'); fr--; }
    while (fc < c) { this.add('key ArrowRight 1', 'frames 1'); fc++; }
    while (fc > c) { this.add('key ArrowLeft 1', 'frames 1'); fc--; }
    this.focus = cell;
  }
  enter(wait) { this.add('key Enter 1', `frames ${wait}`); }
  write(name) { writeFileSync(`${ROOT}tests/native/${name}`, this.lines.join('\n') + '\n'); console.log(`wrote tests/native/${name} (${this.lines.length} lines)`); }
}

/** Plays journey stage `idx` to its end by keys; returns the final status. */
function playStage(s, idx) {
  const level = journeyLevel(idx);
  let st = createGame(level);
  s.focus = 0; s.cols = level.cols;
  for (let k = 0; k < 400 && st.status === 'active'; k++) {
    const la = legalActions(st);
    let cmd;
    if (la.delivers.length) {
      const d = la.delivers[0];
      cmd = { type: 'deliver', cell: d.cell, request: d.request };
      s.moveTo(d.cell); s.enter(3);
      s.add('click =Requests', 'frames 10', 'click =Deliver selected piece', 'frames 20', 'key Escape 1', 'frames 5');
    } else if (la.merges.length) {
      const m = la.merges.reduce((a, b) => (b.tier > a.tier ? b : a));
      cmd = { type: 'merge', from: m.from, to: m.to };
      s.moveTo(m.from); s.enter(3); s.moveTo(m.to); s.enter(20);
    } else if (la.taps.length) {
      cmd = { type: 'tap', cell: la.taps[0].cell };
      s.moveTo(cmd.cell); s.enter(20);
    } else break;
    const r = applyCommand(st, cmd);
    if (!r.ok) throw new Error(`stage ${idx + 1}: illegal ${JSON.stringify(cmd)}: ${r.error}`);
    st = r.state;
  }
  return st.status;
}

{
  const s = new Script(['Generated by tools/gen-plays.mjs: journey stage 1 (First Shelf) from the Journey list, played by keys to the',
    'results (a greedy player: deliver, else the highest merge, else tap a Field Kit), then Next stage plays stage 2 to its results.'], 5);
  s.add('until 300 Discovery Merge', 'frames 30', 'click =Play', 'until 60 Choose a mode', 'frames 10', 'click Journey', 'until 60 Atelier of Dawn', 'frames 10',
    'save journey', 'click First Shelf', 'until 60 =Start', 'frames 10', 'save setup', 'click =Start', 'until 120 =Ready', 'frames 120', 'save stage-1');
  if (playStage(s, 0) !== 'won') throw new Error('stage 1 not won');
  s.add('until 120 Cabinet restored!', 'frames 150', 'save results-1', 'expect Next stage', 'click =Next stage', 'until 120 =Ready', 'frames 120');
  if (playStage(s, 1) !== 'won') throw new Error('stage 2 not won');
  s.add('until 120 Cabinet restored!', 'frames 30', 'save results-2', 'click =Home', 'until 60 2 / 40 stages restored');
  s.write('journey-stages.play');
}
