// score-script.js — Discovery Merge's StarHermit game script (starhermit.txt
// server=score-script.js): the authority on what a finished ranked round
// scores. The client opens a practice session (POST /games/{slug}/sessions/ai)
// and sends what it played on the gameplay socket:
//   { type: 'result', mode: 'journey'|'daily'|'challenge', ref, commands, elapsedSeconds }
// This script builds the level from its own copy of the content (Journey stage
// index, the daily's UTC date — today or yesterday by the host clock — or the
// challenge id), replays the command log through its own copy of the rules
// (every command must be legal), and computes the score itself: the rules'
// total plus, on a win, the time bonus under par. The only client figure is
// the round's active time, and it is never taken below the rules' floor (each
// accepted action locks input for 0.26 s, so n actions take at least
// n × 0.26 s). It posts that score to the high-score board, acknowledges it to
// the player and ends the session. Runs in the platform's Jint sandbox: one
// file, no imports, no Date/Math.random (tools/build-score-script.mjs writes
// the RULES block from src/).
