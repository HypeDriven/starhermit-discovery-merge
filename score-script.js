var MAX_COMMANDS = 5000;
var ACTION_LOCK_S = 0.26;

function valid(board, v) {
  if (typeof v !== 'number' || !isFinite(v)) return false;
  if (board.scoreType !== 'decimal' && Math.floor(v) !== v) return false;
  if (board.minScore != null && v < board.minScore) return false;
  if (board.maxScore != null && v > board.maxScore) return false;
  return true;
}

function utcDate(ms) {
  var days = Math.floor(ms / 86400000);
  // Civil date from days since 1970-01-01 (Howard Hinnant's algorithm).
  var z = days + 719468, era = Math.floor(z / 146097), doe = z - era * 146097;
  var yoe = Math.floor((doe - Math.floor(doe / 1460) + Math.floor(doe / 36524) - Math.floor(doe / 146096)) / 365);
  var y = yoe + era * 400, doy = doe - (365 * yoe + Math.floor(yoe / 4) - Math.floor(yoe / 100));
  var mp = Math.floor((5 * doy + 2) / 153), d = doy - Math.floor((153 * mp + 2) / 5) + 1, m = mp < 10 ? mp + 3 : mp - 9;
  if (m <= 2) y++;
  return y + '-' + (m < 10 ? '0' : '') + m + '-' + (d < 10 ? '0' : '') + d;
}

/** The level a claim names, built from this script's content; null when it is not a ranked board. */
function levelFor(mode, ref, now) {
  if (mode === 'journey') {
    if (typeof ref !== 'number' || Math.floor(ref) !== ref || ref < 0 || ref >= Content.JOURNEY_COUNT) return null;
    return Content.journeyLevel(ref);
  }
  if (mode === 'daily') {
    // The round may have started before midnight UTC: today or yesterday.
    if (ref !== utcDate(now) && ref !== utcDate(now - 86400000)) return null;
    return Content.dailyLevel(ref);
  }
  if (mode === 'challenge') {
    for (var i = 0; i < Content.CHALLENGES.length; i++) if (Content.CHALLENGES[i].id === ref) return Content.challengeLevel(ref);
    return null;
  }
  return null;
}

/** The score the round earned, or null when the claim does not hold. */
function judge(data, now) {
  var level = levelFor(data.mode, data.ref, now);
  if (!level) return null;
  var commands = data.commands;
  if (!Array.isArray(commands) || commands.length > MAX_COMMANDS) return null;
  var state = Rules.createGame(level);
  for (var i = 0; i < commands.length; i++) {
    var c = commands[i];
    if (!c || typeof c !== 'object' || Array.isArray(c)) return null;
    if (state.status !== 'active') return null;
    var r = Rules.applyCommand(state, c);
    if (!r.ok) return null;
    state = r.state;
  }
  if (state.status === 'active') return null; // the round never ended
  var claimed = Number(data.elapsedSeconds);
  var floor = Math.floor(commands.length * ACTION_LOCK_S);
  var elapsed = isFinite(claimed) ? Math.max(Math.round(claimed), floor) : floor;
  var bonus = state.status === 'won' ? Rules.timeBonus(level.parSeconds, elapsed) : 0;
  return Rules.totalScore(state) + bonus;
}

globalThis.game = {
  tickRateHz: 0,

  createSession: function (ctx) {
    return { ok: true, sessionState: { startedAt: ctx.now, summary: { status: 'active' } } };
  },

  onPlayerMessage: function (ctx) {
    var data = ctx.message.data || {};
    if (data.type !== 'result') return { ok: false, error: 'Unknown command' };
    var from = ctx.message.from;
    var score = null;
    try { score = judge(data, ctx.now); } catch (e) { score = null; }
    var scores = {}, accepted = [];
    if (score !== null && valid(BOARDS['high-score'], score)) {
      scores['high-score'] = {};
      scores['high-score'][from] = score;
      accepted.push('high-score');
    }
    var state = ctx.sessionState || {};
    state.summary = { status: 'finished' };
    return {
      ok: true,
      sessionState: state,
      scores: scores,
      broadcast: [{ to: [from], data: { type: 'result-ack', accepted: accepted, score: score } }],
      result: { kind: 'finished', reason: 'result' }
    };
  },

  onTick: function () { return { ok: true }; }
};
